CREATE TABLE users (
                       id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username      VARCHAR(30)  NOT NULL UNIQUE,
                       email         VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
                       bio           VARCHAR(500),
                       created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE titles (
                        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        tmdb_id      BIGINT       NOT NULL,
                        media_type   VARCHAR(20)  NOT NULL,
                        title        VARCHAR(255) NOT NULL,
                        release_year INTEGER,
                        poster_path  VARCHAR(255),
                        overview     TEXT,
                        created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
                        CONSTRAINT uq_titles_tmdb UNIQUE (tmdb_id, media_type),
                        CONSTRAINT chk_titles_media_type CHECK (media_type IN ('MOVIE', 'SERIES'))
);

CREATE TABLE reviews (
                         id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                         title_id   BIGINT      NOT NULL REFERENCES titles (id),
                         rating     INTEGER     NOT NULL,
                         content    TEXT,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                         updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                         CONSTRAINT uq_reviews_user_title UNIQUE (user_id, title_id),
                         CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 10)
);

CREATE INDEX idx_reviews_title_id ON reviews (title_id);
CREATE INDEX idx_reviews_created_at ON reviews (created_at DESC);